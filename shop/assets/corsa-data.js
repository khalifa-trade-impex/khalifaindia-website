  /* Selling price always recomputes from MRP and the SKU's own discount, so a
     discount change can never leave a stale price behind. Never exceeds MRP. */
  PRODUCTS.forEach(function (p) {
    if (p.mrp == null) { p.price = null; return; }
    var d = typeof p.discountPct === 'number' ? p.discountPct : RULES.defaultDiscountPct;
    p.price = Math.min(p.mrp, Math.round(p.mrp * (1 - d / 100)));
  });

  /* A SKU is purchasable only when it has a price AND is explicitly AVAILABLE.
     'NOT SET' is treated as not purchasable — availability must be confirmed
     before anything can be sold. */
  PRODUCTS.forEach(function (p) {
    if (p.availability === 'NOT SET') p.availability = RULES.defaultAvailability;
  });

  function purchasable(p) { return p.price != null && p.availability === 'AVAILABLE'; }

  /* ---------------------------------------------------------------- overrides
     Admin Dashboard writes field-level overrides here. They are applied over
     the baked catalogue at load, so a saved Product Name immediately drives the
     card title, detail heading, Similar Products and order lines.
     IMPORTANT: localStorage is per-browser. To publish edits to real visitors,
     Admin > Export, then paste the JSON into OVERRIDES below and redeploy. */
  var OVERRIDES = {};   // <-- paste exported JSON here to publish permanently

  var OV_KEY = 'kti_corsa_overrides_v1';
  function readOverrides() {
    var live = {};
    try { live = JSON.parse(localStorage.getItem(OV_KEY) || '{}'); } catch (e) { live = {}; }
    var merged = {};
    Object.keys(OVERRIDES).forEach(function (k) { merged[k] = Object.assign({}, OVERRIDES[k]); });
    Object.keys(live).forEach(function (k) { merged[k] = Object.assign({}, merged[k] || {}, live[k]); });
    return merged;
  }
  function applyOverrides() {
    var ov = readOverrides();
    PRODUCTS.forEach(function (p) {
      var o = ov[p.sku];
      if (!o) return;
      Object.keys(o).forEach(function (f) {
        if (f === 'sku') return;                    // SKU is never overwritable
        if (o[f] === '' || o[f] == null) return;
        p[f] = o[f];
      });
      if (o.mrp != null || o.discountPct != null) {
        var mrp = Number(p.mrp), pct = Number(p.discountPct);
        if (!isNaN(mrp) && !isNaN(pct)) p.price = Math.round(mrp * (1 - pct / 100));
      }
    });
  }
  applyOverrides();

